-- Husay account and study storage. Run the entire file in Supabase SQL Editor.
-- Safe to rerun: creates missing tables/columns, retains existing rows.
-- Register through the application: usernames and password hashes go in AccountProfiles.
-- Do not INSERT plaintext passwords. The .NET app creates secure password hashes.
-- Restart the .NET app afterward to initialize sa and its password hash.
BEGIN;
SET LOCAL search_path TO public;
CREATE TABLE IF NOT EXISTS "Sets" (
  "Id" uuid PRIMARY KEY, "Owner" varchar(64) NOT NULL,
  "Title" text NOT NULL, "Category" text NOT NULL, "Level" text NOT NULL,
  "Difficulty" text NOT NULL, "Source" text NOT NULL, "Count" integer NOT NULL,
  "Saved" boolean NOT NULL DEFAULT false, "Created" timestamptz NOT NULL DEFAULT now(),
  "Questions" text NOT NULL DEFAULT '[]', "Progress" text NOT NULL DEFAULT '[]', "Focus" text NOT NULL DEFAULT '');
CREATE INDEX IF NOT EXISTS "IX_Sets_Owner_Saved" ON "Sets" ("Owner", "Saved");
CREATE TABLE IF NOT EXISTS "BankQuestions" (
  "Id" uuid PRIMARY KEY, "Owner" varchar(64) NOT NULL, "Fingerprint" varchar(64) NOT NULL,
  "Category" varchar(64) NOT NULL, "Level" varchar(32) NOT NULL, "Difficulty" varchar(16) NOT NULL,
  "Source" varchar(200) NOT NULL, "Data" text NOT NULL);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_BankQuestions_Owner_Fingerprint" ON "BankQuestions" ("Owner", "Fingerprint");
CREATE TABLE IF NOT EXISTS "AccountProfiles" (
  "Id" varchar(64) PRIMARY KEY, "Username" varchar(30) NOT NULL, "Email" varchar(254) NOT NULL);
ALTER TABLE "AccountProfiles" ADD COLUMN IF NOT EXISTS "Role" text NOT NULL DEFAULT 'User';
ALTER TABLE "AccountProfiles" ADD COLUMN IF NOT EXISTS "PasswordHash" text NOT NULL DEFAULT '';
ALTER TABLE "AccountProfiles" ADD COLUMN IF NOT EXISTS "MustChangePassword" boolean NOT NULL DEFAULT false;
CREATE UNIQUE INDEX IF NOT EXISTS "IX_AccountProfiles_Username" ON "AccountProfiles" ("Username");
CREATE TABLE IF NOT EXISTS "DataProtectionKeys" (
  "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "FriendlyName" text NULL, "Xml" text NULL);
ALTER TABLE "Sets" ADD COLUMN IF NOT EXISTS "Progress" text NOT NULL DEFAULT '[]';
ALTER TABLE "Sets" ADD COLUMN IF NOT EXISTS "Focus" text NOT NULL DEFAULT '';
ALTER TABLE "AccountProfiles" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "DataProtectionKeys" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "Sets" ENABLE ROW LEVEL SECURITY;
ALTER TABLE "BankQuestions" ENABLE ROW LEVEL SECURITY;
COMMIT;

-- Confirm the application tables exist:
SELECT table_name FROM information_schema.tables
WHERE table_schema = 'public'
AND table_name IN ('AccountProfiles', 'DataProtectionKeys', 'Sets', 'BankQuestions')
ORDER BY table_name;
